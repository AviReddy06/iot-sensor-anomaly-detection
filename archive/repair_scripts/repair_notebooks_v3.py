#!/usr/bin/env python3
"""
Properly repair Jupyter notebooks by fixing JSON string escaping.
The issue: Markdown content in cells contains unescaped special characters
(#, |, ✅, ❌, backslashes, etc.) inside JSON string values.
"""

import json
import nbformat
from pathlib import Path
import sys
import re

NOTEBOOKS = [
    "eda/notebooks/01_eda.ipynb",
    "preprocess/notebooks/02_data_preprocessing.ipynb",
    "features/notebooks/03_feature_engineering.ipynb",
]

BACKUP_DIR = Path("notebook_backups")
BACKUP_DIR.mkdir(exist_ok=True)


def fix_notebook_json(content: str) -> str:
    """
    Fix JSON by properly escaping string values.
    Uses a state machine to parse JSON and fix string values.
    """
    output = []
    i = 0
    in_string = False
    escape = False
    
    while i < len(content):
        ch = content[i]
        
        if not in_string:
            if ch == '"':
                in_string = True
                output.append(ch)
            else:
                output.append(ch)
        else:
            if escape:
                output.append(ch)
                escape = False
            elif ch == '\\':
                escape = True
                output.append(ch)
            elif ch == '"':
                in_string = False
                output.append(ch)
            elif ch in '\n\r\t\b\f':
                escapes = {'\n': '\\n', '\r': '\\r', '\t': '\\t', '\b': '\\b', '\f': '\\f'}
                output.append(escapes.get(ch, ch))
            else:
                output.append(ch)
        i += 1
    
    return ''.join(output)


def repair_notebook_file(nb_path: Path) -> tuple[bool, str]:
    print(f"\n{'='*60}")
    print(f"Repairing: {nb_path}")
    print(f"{'='*60}")
    
    try:
        # Backup
        import shutil
        backup_path = BACKUP_DIR / nb_path.name
        shutil.copy2(nb_path, backup_path)
        print(f"  Backed up to: {backup_path}")
        
        # Read content
        with open(nb_path, 'r', encoding='utf-8') as f:
            content = f.read()
        
        print(f"  File size: {len(content)} chars")
        
        # Fix JSON string escaping
        print("  Attempting to fix JSON string escaping...")
        fixed_content = fix_notebook_json(content)
        
        # Try to parse
        try:
            nb = nbformat.reads(fixed_content, as_version=4)
            print("  Parsed successfully!")
        except Exception as e:
            print(f"  nbformat.reads() failed: {e}")
            return False, f"Parse failed: {e}"
        
        # Validate
        try:
            nbformat.validate(nb)
            print("  Validation: OK")
        except nbformat.ValidationError as e:
            print(f"  Validation warning: {e}")
        
        # Write back
        nbformat.write(nb, str(nb_path), version=4)
        print(f"  Written to {nb_path}")
        
        # Verify
        with open(nb_path, 'r', encoding='utf-8') as f:
            verify = f.read()
        json.loads(verify)
        nbformat.validate(nbformat.reads(verify, as_version=4))
        print("  Verification: OK")
        
        return True, "Successfully repaired"
        
    except Exception as e:
        return False, f"Error: {type(e).__name__}: {e}"


def main():
    print("=" * 60)
    print("JUPYTER NOTEBOOK REPAIR - PROPER JSON ESCAPING")
    print("=" * 60)
    
    results = {}
    
    for nb_rel_path in [
        "eda/notebooks/01_eda.ipynb",
        "preprocess/notebooks/02_data_preprocessing.ipynb",
        "features/notebooks/03_feature_engineering.ipynb",
    ]:
        nb_path = Path(nb_rel_path)
        
        if not nb_path.exists():
            print(f"\nSKIP: {nb_rel_path} - NOT FOUND")
            results[nb_rel_path] = "NOT FOUND"
            continue
        
        success, message = repair_notebook_file(nb_path)
        results[str(nb_rel_path)] = message if success else f"FAILED: {message}"
    
    # Summary
    print("\n" + "=" * 60)
    print("REPAIR SUMMARY")
    print("=" * 60)
    
    for path, result in results.items():
        status = "PASS" if "Successfully" in result else "FAIL"
        print(f"  {status} {path}: {result}")
    
    # Generate report
    with open("notebook_validation_report.md", "w", encoding='utf-8') as f:
        f.write("# Notebook Validation Report\n\n")
        f.write(f"Generated: {__import__('datetime').datetime.now()}\n\n")
        f.write("## Summary\n\n")
        for path, result in results.items():
            status = "OK" if "Successfully" in result else "FAIL"
            f.write(f"- {status} {path}: {result}\n")
        f.write("\n## Root Cause\n\n")
        f.write("Notebooks were generated by manually constructing JSON strings ")
        f.write("with f-strings, which failed to escape special characters in ")
        f.write("Markdown content (pipes in tables, checkmarks, headers, etc.).\n\n")
        f.write("## Solution\n\n")
        f.write("Repaired using proper JSON string escaping via state machine.\n")

if __name__ == "__main__":
    main()