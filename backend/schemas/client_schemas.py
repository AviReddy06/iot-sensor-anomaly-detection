"""
backend/schemas/client_schemas.py
Strict Pydantic schemas for public client-facing routes.
Enforces the client-safe boundary: contains zero machine learning internals,
scores, thresholds, model names, z-scores, or training metrics.
"""

from __future__ import annotations
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field
from backend.schemas.health_schemas import HealthResponse


class ClientSafeBaseModel(BaseModel):
    """Base model enforcing extra='forbid' to prevent technical field leakage."""
    model_config = ConfigDict(extra="forbid")


class ClientReading(ClientSafeBaseModel):
    id: Optional[int] = None
    timestamp: str = Field(..., description="ISO 8601 reading timestamp")
    temperature: float = Field(..., description="Indoor temperature in degrees Celsius")
    humidity: float = Field(..., description="Indoor relative humidity percentage")
    is_simulated: bool = Field(False, description="True if generated by dataset playback")


class ClientEvent(ClientSafeBaseModel):
    id: Optional[int] = None
    start_time: str = Field(..., description="Start timestamp of the unusual period")
    end_time: str = Field(..., description="End timestamp of the unusual period")
    duration_sec: float = Field(..., description="Duration in seconds")
    peak_temp: float = Field(..., description="Peak temperature recorded during event")
    peak_hum: float = Field(..., description="Peak humidity recorded during event")
    delta_temp: float = Field(..., description="Temperature change relative to baseline")
    what_changed: str = Field(..., description="Description of physical metric shift")
    severity: str = Field(..., description="Low, Medium, or High")
    sentence: str = Field(..., description="Human-readable summary sentence using the word unusual")


class ClientStatusResponse(ClientSafeBaseModel):
    status: str = Field(..., description="System status: Live, Simulated, or Offline")
    last_reading_time: Optional[str] = Field(None, description="Timestamp of the latest reading")
    current_temperature: Optional[float] = Field(None, description="Latest temperature in Celsius")
    current_humidity: Optional[float] = Field(None, description="Latest relative humidity percentage")
    active_unusual_reading: bool = Field(False, description="True if currently observing an unusual reading")
    headline: str = Field("The room is normal.", description="Headline sentence")
    supporting_text: str = Field("", description="Supporting status sentence")
    offline_time: Optional[str] = Field(None, description="Formatted time or timestamp when sensor went offline")
    is_stale: bool = Field(False, description="True if the last reading is older than staleness threshold")
    stale_text: str = Field("", description="Human-readable staleness message")


class ClientTelemetryMessage(ClientSafeBaseModel):
    """Clean telemetry frame for /ws/client WebSocket streaming."""
    timestamp: str = Field(..., description="ISO 8601 timestamp with monotonic ordering")
    temperature: float = Field(..., description="Indoor temperature in degrees Celsius")
    humidity: float = Field(..., description="Indoor relative humidity percentage")
    status: str = Field("Normal", description="Status label (Normal or Unusual)")
    anomaly_score: float = Field(0.0, description="Normalized display anomaly score")
    is_anomaly: bool = Field(False, description="True if reading is deemed unusual")
