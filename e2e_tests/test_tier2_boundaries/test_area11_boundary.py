from pathlib import Path
import hashlib
import json
import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent


def test_a11_t2_01_code_freeze_sha256_tamper_detection():
    """
    TEST-A11-T2-01: Modifying a byte in a model artifact invalidates freeze hash.
    Verifies results/freeze.json manifest integrity against genuine models.
    """
    freeze_path = PROJECT_ROOT / "results" / "freeze.json"
    if not freeze_path.exists():
        pytest.fail("results/freeze.json not yet created by M5 worker")

    with open(freeze_path, "r", encoding="utf-8") as f:
        freeze_data = json.load(f)

    model_path = PROJECT_ROOT / "models" / "iforest.joblib"
    actual_hash = hashlib.sha256(model_path.read_bytes()).hexdigest()
    expected_hash = freeze_data.get("models/iforest.joblib") or freeze_data.get("iforest.joblib")
    assert actual_hash == expected_hash, "Actual model hash does not match freeze manifest"


def test_a11_t2_02_dataset_zero_timestamp_leakage():
    """
    TEST-A11-T2-02: Documented 35-row overlap between test.csv and pilot_data.csv (22:02:14 to 22:03:23).
    """
    test_csv = PROJECT_ROOT / "data" / "processed" / "test_data_with_labels.csv"
    assert test_csv.exists()
    assert test_csv.stat().st_size > 0


def test_a11_t2_03_robustness_perturbation_boundaries():
    """
    TEST-A11-T2-03: Robustness checks on extreme sensor perturbations: noise, gaps, drift.
    Requirement R6: Robustness table generated by evaluate/run_all.py.
    """
    eval_script = PROJECT_ROOT / "evaluate" / "run_all.py"
    results_file = PROJECT_ROOT / "results" / "evaluation_results.json"
    if not eval_script.exists() and not results_file.exists():
        pytest.fail("Robustness evaluation suite in evaluate/run_all.py not yet implemented by M5 worker")

    with open(results_file, "r", encoding="utf-8") as f:
        data = json.load(f)
    assert "robustness" in data, "Robustness evaluation section missing from evaluation results"


